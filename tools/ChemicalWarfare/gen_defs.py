def gen_ce():
    parts = ["  <!-- Ammo classes shown in CE's ammo tooltips. -->"]
    parts += [ammo_class(g) for g in GASES]
    parts.append("\n  <!-- Left behind by CE projectiles; puts the custom gas on the map, then vents in pulses. -->")
    parts.append(RELEASER_BASE)
    for g in GASES:
        parts.append(releaser(g, "grenade", 0.6))
        parts.append(releaser(g, "launcher", 0.45))
        parts.append(releaser(g, "mortar", 1.0))
    for g in GASES:
        parts.append(f"\n  <!-- ==================== {g.short}: hand grenade ({g.research}) ==================== -->")
        parts.append(grenade(g))
    for g in GASES:
        parts.append(f"\n  <!-- ==================== {g.short}: 40x46mm ({g.research}) ==================== -->")
        parts.append(launcher(g))
    parts.append("\n  <!-- 81mm recipes. CE's ammo injector finds them by name (Make + ammo def) and puts them on the bench\n"
                 "       the ammo base asks for (HSK: heavy ammunition bench). -->")
    parts += [mortar_recipe(g) for g in GASES]
    write("CE/Defs/Ammo_Gas.xml", "\n".join(parts), "Defs")

    shells = ["  <!-- CE 81mm mortar shells. Gas traps are built from them too. -->"]
    shells += [mortar_ce(g) for g in GASES]
    write("CE/Defs/Shells_Gas.xml", "\n\n".join(shells), "Defs")
    remove("CE/Patches/Shells_Gas.xml")

    ops = []
    m81 = "\n".join(f"        <{g.slot.shell}>{g.slot.bullet}</{g.slot.shell}>" for g in GASES)
    g40 = "\n".join(f"        <PGR_Ammo_40x46mm_{g.key}>PGR_Bullet_40x46mm_{g.key}</PGR_Ammo_40x46mm_{g.key}>" for g in GASES)
