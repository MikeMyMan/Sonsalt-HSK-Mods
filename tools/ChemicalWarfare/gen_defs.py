"""Generates the item XML for every gas from gas_data.py.

    py tools/ChemicalWarfare/gen_defs.py

Writes (and overwrites):
  HSK Chemical Warfare/Common/Defs/Items_Bases.xml        abstract bases for canisters, traps, vents, trap implants
  HSK Chemical Warfare/Common/Defs/Items_Gas.xml          canisters, traps, vents
  HSK Chemical Warfare/Common/Defs/Implants_Gas.xml       the three trap implants: hediff, item, crafting and install recipes
  HSK Chemical Warfare/CE/Defs/Ammo_Gas.xml               ammo classes, gas releasers, hand grenades, 40x46mm grenades, recipes
  HSK Chemical Warfare/CE/Defs/Shells_Gas.xml             CE 81mm mortar shells
  HSK Chemical Warfare/CE/Patches/AmmoSets_Gas.xml        the gas ammo joins CE's 81mm and 40x46mm ammo sets
  HSK Chemical Warfare/NoCE/Defs/Shells_Gas.xml           without CE: vanilla mortar shells, research-gated

Def names for the nine Gas Pack gases (PGP_*) are the Gas Pack's own, so a colony can swap the Gas Pack for this
mod and keep its items. Nothing here needs the Gas Pack itself.
"""

import os
import sys
from xml.sax.saxutils import escape

sys.path.insert(0, os.path.dirname(__file__))
from gas_data import GASES, HSK, PAYLOAD  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), "..", "..", "HSK Chemical Warfare")
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_defs.py from tools/gas_data.py. Edit those, not this file. -->\n'


def x(s):
    return escape(s)


def write(rel, body, root_tag):
    path = os.path.normpath(os.path.join(ROOT, rel))
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + f"<{root_tag}>\n{body}\n</{root_tag}>\n")
    print("wrote", os.path.relpath(path, os.path.join(ROOT, "..")))


def color(c):
    return f"({c[0]:.2f}, {c[1]:.2f}, {c[2]:.2f})"


def costs(d, indent):
    pad = " " * indent
    return "\n".join(f"{pad}<{k}>{v}</{k}>" for k, v in d.items())


def ingredients(d, indent):
    pad = " " * indent
    out = []
    for k, v in d.items():
        out.append(f"{pad}<li>\n{pad}  <filter>\n{pad}    <thingDefs>\n{pad}      <li>{k}</li>\n{pad}    </thingDefs>\n"
                   f"{pad}  </filter>\n{pad}  <count>{v}</count>\n{pad}</li>")
    return "\n".join(out)


def fixed_filter(d, indent):
    pad = " " * indent
    items = "\n".join(f"{pad}    <li>{k}</li>" for k in d)
    return f"{pad}<fixedIngredientFilter>\n{pad}  <thingDefs>\n{items}\n{pad}  </thingDefs>\n{pad}</fixedIngredientFilter>"


def research_list(tag, items, indent):
    """items: list of (defName, mayRequire or None)."""
    pad = " " * indent
    lis = "\n".join(f'{pad}  <li MayRequire="{m}">{r}</li>' if m else f"{pad}  <li>{r}</li>" for r, m in items)
    return f"{pad}<{tag}>\n{lis}\n{pad}</{tag}>"


def skills(d, indent):
    pad = " " * indent
    return f"{pad}<skillRequirements>\n" + "\n".join(f"{pad}  <{k}>{v}</{k}>" for k, v in d.items()) + f"\n{pad}</skillRequirements>"


def top(node):
    """A def written for nesting (4 spaces) moved to the top level of a Defs file (2 spaces)."""
    return "\n".join(l[2:] if l.startswith("  ") else l for l in node.splitlines())


def remove(rel):
    """Old generated patch files from when the mod patched the Gas Pack."""
    path = os.path.normpath(os.path.join(ROOT, rel))
    if os.path.exists(path):
        os.remove(path)
        print("removed", os.path.relpath(path, os.path.join(ROOT, "..")))


# ---------------------------------------------------------------- prices

def grenade_value(g):     # 5 per canister + 10 steel + 1 component
    return round((g.canister_value + 10 * 1.9 + 32) / 5 * 1.25, 1)


def launcher_value(g):    # 10 per canister + 12 steel + 1 component + 4 chemfuel
    return round((g.canister_value + 12 * 1.9 + 32 + 4 * 2.3) / 10 * 1.25, 1)


def mortar_value(g):      # 1 canister + 20 steel + 1 component + 5 chemfuel
    return round((g.canister_value + 20 * 1.9 + 32 + 5 * 2.3) * 1.15)


def vent_cost(g):
    c = {"ComponentIndustrial": 5, "Steel": 20}
    for k, v in g.vent_extra.items():
        c[k] = c.get(k, 0) + v
    return c


# ---------------------------------------------------------------- descriptions

def gas_block(g):
    return (f"{g.lore}\\n\\n{g.effects}\\n\\n"
            f"Lethality {g.lethality}. Complexity {g.complexity}. Research: {g.tier}.")


def desc(kind, g):
    lead = {
        "canister": f"A pressurized canister of {g.label}. Load it into a {g.label} vent, or use it to make {g.label} "
                    f"traps, grenades and shells. It bursts if destroyed.",
        "trap": f"A buried canister rig that bursts into a dense {g.label} cloud when an enemy comes close.",
        "vent": f"A powered vent that meters {g.label} from loaded canisters into the area around it. Switch it off to "
                f"stop the flow. The gas spreads through open doors and other vents.",
        "grenade": f"A hand grenade packed with {g.label}. It lands, hisses for two seconds, then bursts into a small "
                   f"cloud and keeps venting briefly.",
        "launcher": f"A 40x46mm launcher grenade with a small {g.label} charge. Bursts on impact.",
        "mortar": f"An 81mm mortar shell filled with {g.label}. Bursts into a large cloud on impact and keeps venting "
                  f"for a few seconds. Also used to build {g.label} gas traps.",
        "mortar_vanilla": f"A mortar shell filled with {g.label}. Bursts into a large cloud on impact. Also used to "
                          f"build {g.label} gas traps.",
        "implant": f"A chest implant that turns its host into a last weapon: when the host dies it ruptures and "
                   f"releases a {g.label} cloud.",
    }[kind]
    return x(lead + "\\n\\n" + gas_block(g))


