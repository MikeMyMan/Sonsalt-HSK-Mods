# Edit the table below (defName = research list, plus a one-line reason), run this, then Sync-ToGame.ps1 and test.
# Reasoning per building: README.md (HSK Zero Research Start).
$rules = [ordered]@{
  # batch 1 (2026-10-22)
  'TrapSpike'                 = @(@('Fortification_B1'), 'spike trap (HSK deadfall: medieval components, mechanism, wire) - same tier as sandbags / reinforced ditch')
  'Turret_Autoloader_Bullets' = @(@('SniperTurret'), 'bullets autoloader - first turrets using its calibers are M240B / M2 Browning (Heavy turrets I; implies Electronics II for its parts)')
  'Turret_Autoloader_Shells'  = @(@('Mortars'), 'shells autoloader - first turrets using its shells are 81mm mortar / 90mm flak (Artillery I; implies Electronics II)')
  'IlluminationTurret_Turret' = @(@('Turrets_31','Pistols_C2'), 'Watcher 2.5 illumination turret - first turret research (implies Guns I for weapon parts) + Pistols II for flare ammo')
  'FabricationBench'          = @(@('Craft_0'), 'hand assembling workbench - HSK sets researchPrerequisites IsNull; Craft_0 unlocks its core recipes (components, wires)')
  'VentilationFilter'         = @(@('AirConditioning','DrugProduction'), 'Watcher 2.5 "Active gas cleaning CO" - same research as the vent (Temperature control III) + Drugs IV for its fuel (activated carbon)')
  # batch 2 (2026-10-22)
  'PPC'                       = @(@('RimatomicsActivate'), 'Rimatomics PPC - really unlocked by Rimatomics research "Energy Weapons"; vanilla gate is a safety net (the Rimatomics bench needs it anyway)')
  'RimatomicsPlusPlus_PPHC'   = @(@('RimatomicsActivate'), 'Rimatomics++ PPHC - really unlocked by Rimatomics research "Hypercapacitors"; vanilla gate is a safety net')
  'SolarWeb-Stratum-RotaryTurbineVent' = @(@('AirConditioning'), 'rooftop rotary turbine vent - a vent (same research as the closable vent); industrial components')
  'VG_SaltMine'               = @(@('Mining_B1'), 'salt mine - digging salt from rough stone is mining (Mining I); other salt sources need Chemistry / Ceramics')
  'SilagePile'                = @(@('Animal_A2'), 'silage pile - making silage at the butcher table / kitchen needs Animal husbandry II')
  'LeatherworkerTable'        = @(@('Apparel_A1'), 'leatherworker table - nearly all its recipes need Apparel production I')
}
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('<?xml version="1.0" encoding="utf-8"?>')
[void]$sb.AppendLine('<Patch>')
[void]$sb.AppendLine('  <!-- Generated by tools\Build-ResearchGates.ps1 (edit the table there, not this file).')
[void]$sb.AppendLine('       Research gates for buildings that HSK 1.7 / addons leave without any research, so they were available from')
[void]$sb.AppendLine('       day one in the zero-research scenarios. Each def: replace researchPrerequisites if the node exists (HSK uses')
[void]$sb.AppendLine('       IsNull="True" on the workbench), otherwise add it; skipped if the def is absent.')
[void]$sb.AppendLine('       Reasoning per building: README.md -->')
foreach ($d in $rules.Keys) {
  $li = ($rules[$d][0] | % { "<li>$_</li>" }) -join ''
  $xp = "Defs/ThingDef[defName=`"$d`"]"
  [void]$sb.AppendLine('')
  [void]$sb.AppendLine("  <!-- $($rules[$d][1]) -->")
  [void]$sb.AppendLine('  <Operation Class="PatchOperationConditional">')
  [void]$sb.AppendLine("    <xpath>$xp/researchPrerequisites</xpath>")
  [void]$sb.AppendLine('    <match Class="PatchOperationReplace">')
  [void]$sb.AppendLine("      <xpath>$xp/researchPrerequisites</xpath>")
  [void]$sb.AppendLine("      <value><researchPrerequisites>$li</researchPrerequisites></value>")
  [void]$sb.AppendLine('    </match>')
  [void]$sb.AppendLine('    <nomatch Class="PatchOperationConditional">')
  [void]$sb.AppendLine("      <xpath>$xp</xpath>")
  [void]$sb.AppendLine('      <match Class="PatchOperationAdd">')
  [void]$sb.AppendLine("        <xpath>$xp</xpath>")
  [void]$sb.AppendLine("        <value><researchPrerequisites>$li</researchPrerequisites></value>")
  [void]$sb.AppendLine('      </match>')
  [void]$sb.AppendLine('    </nomatch>')
  [void]$sb.AppendLine('  </Operation>')
}
[void]$sb.AppendLine('</Patch>')
$out = Join-Path (Split-Path $PSScriptRoot -Parent) 'HSK Zero Research Start\Patches\HSK_ResearchGates.xml'
[IO.File]::WriteAllText($out, $sb.ToString(), (New-Object Text.UTF8Encoding $false))
[xml](Get-Content -LiteralPath $out -Raw) | Out-Null
"written $out ($($rules.Count) buildings)"
