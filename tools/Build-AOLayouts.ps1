# Regenerates HSK Outposts\AdditionalOutposts\Patches\AO_Layouts_HSK.xml (in this repo) from VOE: Additional Outposts' layouts.
# Re-run after an Additional Outposts update, then Sync-ToGame.ps1 and test.
# -AdditionalOutposts: folder of the VOE: Additional Outposts mod (Workshop item 2873841790).
param([string]$AdditionalOutposts = 'D:\SteamLibrary\steamapps\workshop\content\294100\2873841790')
$src = Join-Path $AdditionalOutposts '1.4\Defs\StructureLayoutDefs\Outposts.xml'
$out = Join-Path (Split-Path $PSScriptRoot -Parent) 'HSK Outposts\AdditionalOutposts\Patches\AO_Layouts_HSK.xml'
$doc = New-Object Xml.XmlDocument; $doc.Load($src)
$map = [ordered]@{
  'Wall_WoodLog'='LogWall_PineLog'; 'Door_WoodLog'='Door_WoodPlank'; 'FenceGate_WoodLog'='FenceGate_WoodPlank'; 'Fence_WoodLog'='Fence_WoodPlank'
  'Bed_WoodLog'='Bed_Cloth'; 'DiningChair_WoodLog'='DiningChair_Cloth'; 'Column_WoodLog'='Column_BlocksGranite'
  'Stool_WoodLog'='Stool_WoodPlank'; 'Table1x2c_WoodLog'='Table1x2c_WoodPlank'; 'Pew_WoodLog'='Pew_WoodPlank'; 'EndTable_WoodLog'='EndTable_WoodPlank'
  'Shelf_WoodLog'='Shelf_WoodPlank'; 'Lectern_WoodLog'='Lectern_WoodPlank'; 'Blackboard_WoodLog'='Blackboard_WoodPlank'; 'SculptureGrand_WoodLog'='SculptureGrand_WoodPlank'
}
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('<?xml version="1.0" encoding="utf-8"?>'); [void]$sb.AppendLine('<Patch>')
[void]$sb.AppendLine('  <!-- Generated by tools\Build-AOLayouts.ps1 from VOE: Additional Outposts 1.4/Defs/StructureLayoutDefs/Outposts.xml.')
[void]$sb.AppendLine('       HSK: walls can''t be logs (Vile cabin wall from pine logs instead), beds/chairs are fabric, furniture is planks,')
[void]$sb.AppendLine('       vanilla carpets are removed (plank floor instead). Each layout is replaced whole with the remapped copy. -->')
foreach ($d in $doc.SelectNodes('/Defs/KCSG.StructureLayoutDef')) {
  $t = $d.OuterXml
  foreach ($k in $map.Keys) { $t = $t -replace "(?<=[,>])$([regex]::Escape($k))(?=[,<_])", $map[$k] }
  $t = $t -replace '(?<=[,>])CarpetRed(?=[,<])', 'WoodPlankFloor'
  $xp = "Defs/KCSG.StructureLayoutDef[defName=`"$($d.defName)`"]"
  [void]$sb.AppendLine("  <Operation Class=`"PatchOperationConditional`">`n    <xpath>$xp</xpath>`n    <match Class=`"PatchOperationReplace`">`n      <xpath>$xp</xpath>`n      <value>`n$t`n      </value>`n    </match>`n  </Operation>")
}
[void]$sb.AppendLine('</Patch>')
[IO.File]::WriteAllText($out, $sb.ToString(), (New-Object Text.UTF8Encoding $false))
"written $out"
